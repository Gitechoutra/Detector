"""Insert-if-missing helpers. Seeders work on a plain SQLAlchemy Connection so
the same code runs inside an Alembic migration and from `flask seed`."""
import sqlalchemy as sa


def exists(conn, table, column, value):
    return conn.execute(sa.text(f'SELECT 1 FROM {table} WHERE {column} = :v LIMIT 1'), {'v': value}).first()


def _model_defaults(table, row):
    """Python-side column defaults from the models (created_at=now(), flags,
    statuses...). Raw SQL skips them, and the autogenerated schema has no
    server defaults, so NOT NULL columns would otherwise be rejected."""
    from portal.extensions import db
    import portal.models  # noqa: F401  (registers every table on the metadata)

    model_table = db.metadata.tables.get(table)
    if model_table is None:
        return {}
    filled = {}
    for col in model_table.columns:
        if col.name in row or col.default is None:
            continue
        arg = col.default.arg
        if col.default.is_callable:
            try:
                filled[col.name] = arg(None)
            except TypeError:
                filled[col.name] = arg()
        elif col.default.is_scalar:
            filled[col.name] = arg
    return filled


def insert(conn, table, row):
    row = {**_model_defaults(table, row), **row}
    cols = ', '.join(row)
    params = ', '.join(f':{c}' for c in row)
    conn.execute(sa.text(f'INSERT INTO {table} ({cols}) VALUES ({params})'), row)


def id_of(conn, table, column, value):
    return conn.execute(sa.text(f'SELECT id FROM {table} WHERE {column} = :v'), {'v': value}).scalar()
