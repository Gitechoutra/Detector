import { useState } from 'react';
import { Empty, ErrorNote, Loading, OutcomeBadge, PageHead, RiskScore, RuleChips } from '../../components/ui';
import { useApi } from '../../hooks';
import { dateTime, money } from '../../utils/format';

const OTP = { NOT_SENT: ['Not sent', 'b-slate'], SENT: ['Sent', 'b-amber'], VERIFIED: ['Verified', 'b-green'],
  FAILED: ['Failed', 'b-red'], EXPIRED: ['Expired', 'b-slate'] };
const ANSWER = { YES: ['YES', 'b-green'], NO: ['NO', 'b-red'] };

/** What the fraud engine actually recorded – flagged payments, flagged and blocked
 *  receiver accounts. Nothing on this page is typed in, hard-coded or seeded. */
export default function FraudRecords() {
  const { data, error } = useApi('/frauder/records', null, { interval: 5000 });
  const [tab, setTab] = useState('transactions');

  if (!data) return error ? <ErrorNote error={error} /> : <Loading />;
  return (
    <>
      <PageHead title="Fraud detection records"
                subtitle="Generated by the application: every payment on which a risk factor was detected, the owner’s YES/NO, the OTP check, and the receiver accounts that were flagged or blocked." />

      <div className="tabs" role="tablist">
        {[['transactions', 'Flagged transactions'], ['blocked', 'Blocked receivers'], ['flagged', 'Flagged receivers']].map(([k, l]) => (
          <button key={k} type="button" role="tab" aria-selected={tab === k} className={`tab ${tab === k ? 'on' : ''}`} onClick={() => setTab(k)}>{l}</button>
        ))}
      </div>

      {tab === 'transactions' && (
        <div className="card mt-8">
          {data.transactions.length === 0 ? <Empty icon="🛡️" title="No detections yet">Records appear here when a risk factor is detected on a payment.</Empty> : (
            <div className="table-wrap">
              <table className="table">
                <thead><tr><th>Detected</th><th>Transaction</th><th>Sender → Receiver</th><th className="right">Amount</th><th>Risk score</th><th>Risk factors</th><th>User answer</th><th>OTP</th><th>Outcome</th></tr></thead>
                <tbody>
                  {data.transactions.map((r) => (
                    <tr key={r.transaction_id}>
                      <td className="small nowrap">{dateTime(r.detected_at)}</td>
                      <td className="small"><span className="mono">{r.txn_ref}</span><div className="muted">{r.source}</div></td>
                      <td className="small">{r.sender} → {r.receiver}
                        <div className="muted mono">{r.receiver_upi}{r.receiver_account_status === 'BLOCKED' && <span className="badge b-red" style={{ marginLeft: 6 }}>blocked</span>}</div></td>
                      <td className="right nowrap">{money(r.amount)}</td>
                      <td><RiskScore score={r.risk_score} />{r.risk_score >= 70 && <div className="small" style={{ color: 'var(--danger)' }}>high risk</div>}</td>
                      <td className="small"><RuleChips rules={r.risk_factors} />
                        {r.risk_factors.map((f) => <div key={f.code} className="muted">{f.code}: {f.reason}</div>)}</td>
                      <td className="small">{r.user_response
                        ? <><span className={`badge ${ANSWER[r.user_response][1]}`}>{ANSWER[r.user_response][0]}</span><div className="muted">{dateTime(r.responded_at)}</div></>
                        : <span className="muted">—</span>}</td>
                      <td className="small">{r.otp ? <span className={`badge ${OTP[r.otp.status][1]}`}>{OTP[r.otp.status][0]}</span> : <span className="muted">—</span>}
                        {r.otp?.attempts > 0 && <div className="muted">{r.otp.attempts} wrong</div>}</td>
                      <td><OutcomeBadge label={r.outcome_label} /></td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </div>
      )}

      {tab === 'blocked' && (
        <div className="card mt-8">
          {data.blocked_receivers.length === 0 ? <Empty icon="✅" title="No receiver has been blocked">A receiver is blocked when the payer’s account owner answers NO.</Empty> : (
            <div className="table-wrap">
              <table className="table">
                <thead><tr><th>Blocked at</th><th>Receiver account</th><th>Transaction</th><th>Risk score</th><th>Risk factors</th><th>Reason</th><th>Status</th></tr></thead>
                <tbody>
                  {data.blocked_receivers.map((b) => (
                    <tr key={b.id}>
                      <td className="small nowrap">{dateTime(b.blocked_at)}</td>
                      <td className="small"><strong>{b.receiver.name}</strong><div className="muted mono">{b.receiver.upi_id} · {b.receiver.account_number}</div></td>
                      <td className="small"><span className="mono">{b.transaction?.txn_ref}</span>
                        <div className="muted">{money(b.transaction?.amount)} from {b.transaction?.sender} · {dateTime(b.transaction?.txn_time)}</div></td>
                      <td><RiskScore score={b.risk_score} /></td>
                      <td><RuleChips rules={b.risk_factors} /></td>
                      <td className="small">{b.reason}<div className="muted">reported by {b.reported_by}</div></td>
                      <td>{b.status === 'ACTIVE'
                        ? <span className="badge b-red">Blocked</span>
                        : <span className="badge b-slate" title={b.lift_reason}>Lifted {dateTime(b.lifted_at)}</span>}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </div>
      )}

      {tab === 'flagged' && (
        <div className="card mt-8">
          {data.flagged_receivers.length === 0 ? <Empty icon="✅" title="No flagged receivers" /> : (
            <div className="table-wrap">
              <table className="table">
                <thead><tr><th>Receiver account</th><th>Reason</th><th>Source</th><th>Flagged at</th><th>Account status</th></tr></thead>
                <tbody>
                  {data.flagged_receivers.map((f) => (
                    <tr key={f.account_id || f.upi_id || f.account_number}>
                      <td className="small"><strong>{f.name || 'Unknown account'}</strong><div className="muted mono">{f.upi_id || f.account_number}</div></td>
                      <td className="small">{f.reason}</td>
                      <td className="small">{f.source === 'AUTO' ? 'Fraud engine' : 'Fraud analyst'}</td>
                      <td className="small nowrap">{dateTime(f.flagged_at)}</td>
                      <td>{f.account_status ? <span className={`badge ${f.account_status === 'ACTIVE' ? 'b-amber' : 'b-red'}`}>{f.account_status === 'ACTIVE' ? 'Flagged' : f.account_status}</span> : '—'}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </div>
      )}
    </>
  );
}
